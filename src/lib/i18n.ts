/**
 * Internationalization (i18n) utility for SelRx.
 *
 * Supports English (en) and French (fr) — the two official working languages
 * of ECOWAS. The active language is read from the Zustand store via a lazy
 * getter, mirroring the currency module's pattern. The value is seeded from
 * the CompanySetup `language` field at app boot.
 *
 * Usage:
 *   import { t } from '@/lib/i18n'
 *   <button>{t('common.save')}</button>
 *
 * Adding a new translation key:
 *   1. Add it to both `en` and `fr` dictionaries below.
 *   2. Use t('category.key') in any component.
 *
 * Missing keys fall back to the English value, then to the key itself,
 * so a missing translation never crashes the UI.
 */

export type LanguageCode = 'en' | 'fr'

export interface LanguageOption {
  code: LanguageCode
  label: string           // Native name shown in pickers ("English", "Français")
  englishLabel: string    // English name ("English", "French")
  flag: string            // Emoji flag for quick visual ID
  bcp47: string           // BCP-47 locale for Intl APIs (en-US, fr-FR)
}

