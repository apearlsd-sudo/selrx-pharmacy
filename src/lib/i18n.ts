const DICTIONARIES: Record<LanguageCode, Dict> = { en, fr }

// ── Lazy store getter (mirrors the currency module's pattern) ────────────
//
// We avoid a direct Zustand import here to prevent circular dependencies.
// The app shell calls initLanguageGetter() once on mount.

let _getLanguageCode: (() => LanguageCode) | null = null

export function initLanguageGetter(getter: () => LanguageCode): void {
  _getLanguageCode = getter
}

function resolveCode(): LanguageCode {
  if (_getLanguageCode) {
    try {
      return _getLanguageCode()
    } catch {
      // fall through to default
    }
  }
  return 'en'
}

/**
 * Translate a key to the currently active language.
 *
 * Missing keys fall back to English, then to the key itself — so a missing
 * translation never throws or shows a blank.
 *
 *   t('common.save')         → 'Save' / 'Enregistrer'
 *   t('common.nonexistent')  → 'common.nonexistent' (the key itself)
 */
export function t(key: string): string {
  const code = resolveCode()
  const dict = DICTIONARIES[code]
  if (dict && key in dict) return dict[key]
  // Fallback to English
  const enDict = DICTIONARIES.en
  if (enDict && key in enDict) return enDict[key]
  // Last resort: the key itself (so a missing key is visible, not blank)
  return key
}

/**
 * Translate a key with simple {placeholder} substitution.
 *
 *   tf('auth.shiftEndedDesc', { name: 'Alice' })
 *     → 'Goodbye, Alice. You have been signed out successfully.'
 *
 * Placeholders are written as {varName} in the dictionary string.
 * Unknown placeholders are left as-is.
 */
export function tf(key: string, vars: Record<string, string | number>): string {
  let s = t(key)
  for (const [k, v] of Object.entries(vars)) {
    s = s.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
  }
  return s
}

/**
 * Type guard — verify a string is a supported LanguageCode.
 */
export function isLanguageCode(value: unknown): value is LanguageCode {
  return value === 'en' || value === 'fr'
}

/**
 * Coerce an unknown value to a LanguageCode, falling back to 'en'.
 */
export function asLanguageCode(value: unknown): LanguageCode {
  return isLanguageCode(value) ? value : 'en'
}

/**
 * Get the active LanguageOption.
 */
export function activeLanguage(): LanguageOption {
  return LANGUAGES[resolveCode()]
}
